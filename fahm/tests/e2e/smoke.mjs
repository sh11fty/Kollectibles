import { createRequire } from 'node:module';
import { startServer } from '../serve.mjs';
const require = createRequire('/opt/node22/lib/node_modules/');
const { chromium } = require('playwright');
const out = process.argv[2] || '/tmp/shots';
import fs from 'node:fs';
fs.mkdirSync(out, { recursive: true });
const { server, port } = await startServer(0);
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 412, height: 860 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
const logs = [];
page.on('console', (m) => { if (['error', 'warning'].includes(m.type())) logs.push(m.type() + ': ' + m.text()); });
page.on('pageerror', (e) => logs.push('PAGEERROR: ' + e.message));
await page.goto(`http://127.0.0.1:${port}/`);
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/01-first.png` });
console.log(logs.join('\n') || 'no console errors');
console.log((await page.evaluate(() => document.body.innerText)).slice(0, 400));
await browser.close();
server.close();
